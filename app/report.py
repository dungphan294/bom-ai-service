"""Generate a Word (.docx) report from a BOM analysis."""

from datetime import date
from io import BytesIO

from docx import Document
from docx.shared import Pt

from .schemas import BomAnalysis


def _table(doc: Document, headers: list[str], rows: list[list[str]]) -> None:
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = "Light Grid Accent 1"
    for cell, text in zip(table.rows[0].cells, headers):
        cell.text = text
    for row in rows:
        for cell, text in zip(table.add_row().cells, row):
            cell.text = text


def _fmt(value: float | None) -> str:
    return "-" if value is None else f"{value:g}"


def build_report(analysis: BomAnalysis, source_name: str) -> bytes:
    s = analysis.summary
    doc = Document()
    doc.styles["Normal"].font.size = Pt(11)

    doc.add_heading("BOM Analysis Report", level=0)
    doc.add_paragraph(f"Source file: {source_name}\nDate: {date.today().isoformat()}")

    doc.add_heading("Summary", level=1)
    doc.add_paragraph(analysis.ai_summary)

    doc.add_heading("Key figures", level=1)
    _table(doc, ["Metric", "Value"], [
        ["BOM lines", str(s.total_lines)],
        ["Total quantity", _fmt(s.total_quantity)],
        ["Total weight (kg)", _fmt(s.total_weight_kg) if s.total_weight_kg is not None else "Incomplete"],
    ])

    if s.weight_by_material_kg:
        doc.add_heading("Weight by material", level=1)
        _table(doc, ["Material", "Weight (kg)"], [[m, _fmt(kg)] for m, kg in s.weight_by_material_kg.items()])

    doc.add_heading("Parts", level=1)
    _table(doc, ["Part number", "Description", "Material", "Qty", "Unit kg", "Total kg"], [
        [i.part_number, i.description, i.material or "-", _fmt(i.quantity),
         _fmt(i.unit_weight_kg), _fmt(i.total_weight_kg)]
        for i in s.items
    ])

    if s.missing_data:
        doc.add_heading("Data issues", level=1)
        for issue in s.missing_data:
            doc.add_paragraph(issue, style="List Bullet")

    doc.add_paragraph().add_run(f"Generated by BOM AI Service (LLM mode: {analysis.llm_mode}).").italic = True

    buf = BytesIO()
    doc.save(buf)
    return buf.getvalue()
